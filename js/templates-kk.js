  function fd(iso) {
    if (!L.parseISO(iso)) return BLANK_DATE;
    return iso.slice(0, 4) + ' жылғы ' + iso.slice(8, 10) + ' ' + MONTHS[+iso.slice(5, 7) - 1];
  }
  function v(x) { return L.isEmpty(x) ? '____________' : String(x).trim(); }
