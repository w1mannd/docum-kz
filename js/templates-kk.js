  function moneyW(t) { return money(t) + ' ' + say(L.moneyWordsKz(t)); }
  function num(value, unit) {
    var n = L.parseInt10(value);
    if (isNaN(n)) return '____ ' + unit;
    return n + ' ' + say(L.intWordsKz(n)) + ' ' + unit;
  }
  function percentW(value) {
    var s = String(value).trim(), n = L.parseInt10(s);
    return s + ' ' + say(isNaN(n) ? L.decimalWordsKz(s) : L.intWordsKz(n)) + ' пайыз';
  }
