    hire: function (d) {
      var prob = L.parseInt10(d.probation) || 0, sal = L.toTiyn(d.salary) || 0;
      var text = '1. Жұмыскер ' + v(d.w_fio) + ' «' + pos(d) + '» лауазымы бойынша жұмысқа қабылдансын. Жұмыстың басталу күні: ' + fd(d.work_start) + '. Жалақы: айына ' + moneyW(sal) + '.';
      text += prob > 0 ? ' Сынақ мерзімі: ' + num(d.probation, MONTH) + '.' : ' Сынақ мерзімі белгіленбейді.';
      return orderHead(d, 'Жұмысқа қабылдау туралы').concat([
        G(),
        P('Негіздеме: еңбек шарты № ' + v(d.contract_no) + ', ' + fd(d.contract_date) + '.'),
        ORDER,
        P(text)
      ], orderSign(d));
    },

    leave: function (d) {
      var r = L.leaveDates(d.leave_start, d.leave_days, d.holidays);
      var kind = d.leave_kind === 'part' ? 'жыл сайынғы ақы төленетін еңбек демалысының бөлігі' : 'жыл сайынғы ақы төленетін еңбек демалысы';
      var out = orderHead(d, 'Жыл сайынғы ақы төленетін еңбек демалысын беру туралы').concat([
        G(),
        ORDER,
        P('1. Жұмыскер ' + v(d.w_fio) + ' (лауазымы: ' + pos(d) + ') үшін ' + kind + ' берілсін. Жұмыс жылы: ' + fd(d.year_from) + ' — ' + fd(d.year_to) + '. Демалыс ұзақтығы: ' + num(d.leave_days, DAYS) + ', кезеңі: ' + fd(d.leave_start) + ' — ' + fd(r && r.end) + '. Жұмысқа шығу күні: ' + fd(r && r.back) + '.'),
        P('2. Еңбек демалысына ақы Қазақстан Республикасы Еңбек кодексінің 92-бабының 4-тармағында белгіленген мерзімде төленсін.')
      ]);
      if (!L.isEmpty(d.leave_basis)) out.push(P('Негіздеме: ' + d.leave_basis.trim() + '.'));
      return out.concat(orderSign(d));
    },

    certificate: function (d) {
      var out = [
        C(v(d.ip_name), true),
        C('Т.А.Ә.: ' + v(d.ip_fio) + ', ЖСН ' + v(d.ip_iin) + ', ' + v(d.ip_addr)),
        G(),
        R(fd(d.date) + ' № ' + v(d.number), v(d.addressee)),
        C(place(d)),
        G(),
        T('АНЫҚТАМА'),
        P('жұмыс орнынан', { center: true }),
        G(),
        P('Осы анықтама ' + v(d.w_fio) + ' «' + pos(d) + '» лауазымы бойынша жұмыс істейтінін растайды. Жұмыс беруші: ' + v(d.ip_name) + '. Жұмыстың басталу күні: ' + fd(d.work_start) + '.')
      ];
      if (!L.isEmpty(d.cert_salary)) out.push(P('Жалақы мөлшері: айына ' + moneyW(L.toTiyn(d.cert_salary) || 0) + '.'));
      out.push(G(), R('Жеке кәсіпкер', '______________ ' + initials(d.ip_fio)), P(MP));
      return out;
    },

    termination: function (d) {
      var out = orderHead(d, 'Еңбек шартын тараптардың келісімі бойынша бұзу туралы').concat([
        G(),
        P('Қазақстан Республикасы Еңбек кодексінің 49-бабының 1) тармақшасына және 50-бабына сәйкес:'),
        ORDER,
        P('1. Еңбек шарты № ' + v(d.contract_no) + ' (' + fd(d.contract_date) + ') жұмыскер ' + v(d.w_fio) + ' (лауазымы: ' + pos(d) + ') тараптардың келісімі бойынша бұзылсын. Бұзу күні: ' + fd(d.term_date) + '.'),
        P('2. Жұмыскерге тиесілі сомалар еңбек шарты тоқтатылғаннан кейін үш жұмыс күнінен кешіктірілмей төленсін.')
      ]);
      var u = L.parseInt10(d.unused_days);
      if (u > 0) out.push(P('3. Пайдаланылмаған жыл сайынғы ақы төленетін еңбек демалысының ' + num(d.unused_days, DAYS) + ' үшін өтемақы төленсін.'));
      return out.concat(orderSign(d));
    }
